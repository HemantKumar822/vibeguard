"""Export backend-owned schemas. Run before openapi-typescript generation."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from backend.api.main import app  # noqa: E402
from backend.core.contracts import Scan, Comparison, Deletion  # noqa: E402


def main():
    target = ROOT/'contracts/openapi.json'
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(app.openapi(), indent=2) + '\n', encoding='utf-8')
    models = {'scan': Scan, 'comparison': Comparison, 'deletion': Deletion}
    lines = ['// Generated by scripts/export_contracts.py. Development data only.',
             'import type { components } from "./api";', '']
    names = []
    for path in sorted((ROOT/'fixtures/contracts').glob('*.json')):
        fixture = json.loads(path.read_text(encoding='utf-8'))
        model = models[fixture['kind']]
        model.model_validate(fixture['data'])
        name = path.stem.replace('-', '_')
        names.append(f'  {{name: {json.dumps(path.stem)}, kind: {json.dumps(fixture["kind"])}, data: {name}}}')
        lines.append(f'const {name} = {json.dumps(fixture["data"], indent=2)} satisfies components["schemas"]["{model.__name__}"];')
    lines.append('export const fixtures = [\n' + ',\n'.join(names) + '\n];')
    out = ROOT/'frontend/src/generated/fixtures.ts'
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print('Exported OpenAPI and validated development fixtures.')


if __name__ == '__main__':
    main()
